import { describe, expect, it } from 'vitest'

import type { ModelFile } from '../types'
import { generateTypes } from './typegen'

const model: ModelFile = {
	version: 1,
	contentTypes: [
		{
			apiId: 'blogPost',
			name: 'Blog post',
			kind: 'page',
			description: 'A post\non the blog',
			fields: [
				{ apiId: 'title', name: 'Title', type: 'text', required: true },
				{ apiId: 'intro', name: 'Intro', type: 'textarea', localized: true },
				{ apiId: 'body', name: 'Body', type: 'richtext' },
				{ apiId: 'readingTime', name: 'Reading time', type: 'number' },
				{ apiId: 'featured', name: 'Featured', type: 'boolean' },
				{ apiId: 'date', name: 'Date', type: 'datetime' },
				{
					apiId: 'category',
					name: 'Category',
					type: 'select',
					description: 'Where it is listed',
					options: [
						{ value: 'news', label: 'News' },
						{ value: "it's", label: 'Quote' },
					],
				},
				{
					apiId: 'tags',
					name: 'Tags',
					type: 'select',
					multiple: true,
					options: [{ value: 'a', label: 'A' }],
				},
				{ apiId: 'image', name: 'Image', type: 'asset' },
				{ apiId: 'gallery', name: 'Gallery', type: 'asset', multiple: true },
				{
					apiId: 'author',
					name: 'Author',
					type: 'reference',
					contentTypes: ['author'],
				},
				{
					apiId: 'related',
					name: 'Related',
					type: 'reference',
					multiple: true,
				},
				{
					apiId: 'sections',
					name: 'Sections',
					type: 'blocks',
					allowedBlocks: ['hero'],
				},
				{ apiId: 'everything', name: 'Everything', type: 'blocks' },
				{ apiId: 'meta', name: 'Meta', type: 'json' },
			],
		},
		{
			apiId: 'author',
			name: 'Author',
			kind: 'data',
			description: null,
			fields: [],
		},
		{
			apiId: 'hero',
			name: 'Hero',
			kind: 'block',
			description: 'The top of a page, */ with a heading',
			fields: [{ apiId: 'heading', name: 'Heading', type: 'text' }],
		},
		{
			apiId: 'asset',
			name: 'Asset',
			kind: 'block',
			description: '',
			fields: [],
		},
	],
}

describe('generateTypes', () => {
	it('writes a type per content type, with a value type per field', () => {
		expect(generateTypes(model))
			.toBe(`// Generated by \`npx @obelism/content types\` from the content model.
// Don't edit: run it again after the model changes.

import type { Asset, Block, Entry, EntryStub, ImproveBlock, RichTextDocument } from '@obelism/content'

/** Blog post (page): A post on the blog */
export type BlogPost = Entry<
	{
		title: string | null
		intro: string | null
		body: RichTextDocument | null
		readingTime: number | null
		featured: boolean | null
		date: string | null
		/** Where it is listed */
		category: 'news' | 'it\\'s' | null
		tags: 'a'[] | null
		image: Asset | null
		gallery: Asset[] | null
		author: Author | EntryStub<'author'> | null
		related: (BlogPost | Author | EntryStub<'blogPost' | 'author'>)[] | null
		sections: (Hero | ImproveBlock<Hero>)[] | null
		everything: (Hero | AssetBlock | ImproveBlock<Hero | AssetBlock>)[] | null
		meta: unknown
	},
	'blogPost'
>

/** Author (data) */
export type Author = Entry<
	Record<never, never>,
	'author'
>

/** Hero (block): The top of a page, *\\/ with a heading */
export type Hero = Block<
	{
		heading: string | null
	},
	'hero'
>

/** Asset (block) */
export type AssetBlock = Block<
	Record<never, never>,
	'asset'
>

export type ContentEntry = BlogPost | Author
export type ContentBlock = Hero | AssetBlock
`)
	})

	it('falls back to the SDK types when a field allows nothing that exists', () => {
		const types = generateTypes({
			version: 1,
			contentTypes: [
				{
					apiId: 'settings',
					name: 'Settings',
					kind: 'data',
					description: 'Site-wide',
					fields: [
						{
							apiId: 'home',
							name: 'Home',
							type: 'reference',
							contentTypes: ['gone'],
						},
						{ apiId: 'footer', name: 'Footer', type: 'blocks' },
					],
				},
			],
		})
		expect(types).toContain('home: Entry | EntryStub | null')
		expect(types).toContain('footer: (Block | ImproveBlock)[] | null')
		expect(types).toContain(
			"import type { Block, Entry, EntryStub, ImproveBlock } from '@obelism/content'",
		)
	})

	it('types shopify fields as ShopifyItem', () => {
		const types = generateTypes({
			version: 1,
			contentTypes: [
				{
					apiId: 'productGrid',
					name: 'Product grid',
					description: 'Products in a grid.',
					kind: 'block',
					fields: [
						{
							apiId: 'collection',
							name: 'Collection',
							type: 'shopify',
							resource: 'collection',
						},
						{
							apiId: 'products',
							name: 'Products',
							type: 'shopify',
							resource: 'product',
							multiple: true,
						},
					],
				},
			],
		})
		expect(types).toMatch(/\tcollection: ShopifyItem \| null\n/)
		expect(types).toMatch(/\tproducts: ShopifyItem\[\] \| null\n/)
		expect(types).toContain("ShopifyItem } from '@obelism/content'")
	})

	it('writes only the header for an empty model', () => {
		expect(generateTypes({ version: 1, contentTypes: [] })).not.toContain(
			'import',
		)
	})
})
