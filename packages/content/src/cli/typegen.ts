import type {
	ContentTypeDefinition,
	FieldDefinition,
	ModelFile,
} from '../types'

// What `content types` writes to content/content-types.ts: a TypeScript type
// per content type, for what the delivery API answers with its defaults (one
// locale, rich text as a document). Pages and data are `Entry<…>`, blocks
// `Block<…>`, every field `| null` (delivery answers null for empty ones).
// Pure.
//
//   const post = await client.getPage<BlogPost>('blog/hello')

// The SDK's types the file imports; a content type whose name would clash
// gets its kind as a suffix (`asset` → `AssetEntry`).
const SDK_TYPES = [
	'Asset',
	'Block',
	'Entry',
	'EntryStub',
	'ImproveBlock',
	'RichTextDocument',
	'ShopifyItem',
] as const

type SdkType = (typeof SDK_TYPES)[number]

// The unions of every entry and block type the file ends with.
const UNION_NAMES = ['ContentEntry', 'ContentBlock'] as const

const quote = (value: string) =>
	`'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`

const union = (members: string[]) => [...new Set(members)].join(' | ')

const list = (type: string, multiple: boolean | undefined) =>
	multiple ? (type.includes(' | ') ? `(${type})[]` : `${type}[]`) : type

// `unknown` (a json field) holds null already.
const nullable = (type: string) =>
	type === 'unknown' ? type : `${type} | null`

// JSDoc, so editors show it on hover.
const comment = (text: string, indent: string) =>
	`${indent}/** ${text.replace(/\s+/g, ' ').trim().replace(/\*\//g, '*\\/')} */\n`

export const generateTypes = (model: ModelFile): string => {
	const types = model.contentTypes
	const blockTypes = types.filter(({ kind }) => kind === 'block')
	const entryTypes = types.filter(({ kind }) => kind !== 'block')
	const used = new Set<SdkType>()
	const use = (name: SdkType) => {
		used.add(name)
		return name
	}

	// apiIds start with a lowercase letter and are unique, so capitalizing
	// keeps them unique.
	const typeName = new Map(
		types.map(({ apiId, kind }) => {
			const name = `${apiId[0]!.toUpperCase()}${apiId.slice(1)}`
			const reserved =
				(SDK_TYPES as readonly string[]).includes(name) ||
				(UNION_NAMES as readonly string[]).includes(name)
			return [
				apiId,
				reserved ? `${name}${kind === 'block' ? 'Block' : 'Entry'}` : name,
			]
		}),
	)

	const known = (
		allowed: string[] | undefined,
		candidates: ContentTypeDefinition[],
	) =>
		allowed
			? candidates.filter(({ apiId }) => allowed.includes(apiId))
			: candidates

	const value = (field: FieldDefinition): string => {
		switch (field.type) {
			case 'text':
			case 'textarea':
			case 'datetime':
				return 'string'
			case 'number':
				return 'number'
			case 'boolean':
				return 'boolean'
			case 'richtext':
				return use('RichTextDocument')
			case 'select':
				return list(
					union(field.options.map((option) => quote(option.value))),
					field.multiple,
				)
			case 'asset':
				return list(use('Asset'), field.multiple)
			case 'reference': {
				// The entry itself, or a stub past the requested depth.
				const targets = known(field.contentTypes, entryTypes)
				const type =
					targets.length === 0
						? `${use('Entry')} | ${use('EntryStub')}`
						: union([
								...targets.map(({ apiId }) => typeName.get(apiId)!),
								`${use('EntryStub')}<${union(targets.map(({ apiId }) => quote(apiId)))}>`,
							])
				return list(type, field.multiple)
			}
			case 'blocks': {
				const allowed = known(field.allowedBlocks, blockTypes)
				const blocks =
					allowed.length === 0
						? use('Block')
						: union(allowed.map(({ apiId }) => typeName.get(apiId)!))
				const improve = `${use('ImproveBlock')}${allowed.length === 0 ? '' : `<${blocks}>`}`
				return list(union([blocks, improve]), true)
			}
			case 'shopify':
				return list(use('ShopifyItem'), field.multiple)
			case 'json':
				return 'unknown'
		}
	}

	const declaration = (type: ContentTypeDefinition) => {
		const wrapper = type.kind === 'block' ? use('Block') : use('Entry')
		const fields = type.fields
			.map(
				(field) =>
					`${field.description ? comment(field.description, '\t\t') : ''}\t\t${field.apiId}: ${nullable(value(field))}\n`,
			)
			.join('')
		const body = fields ? `{\n${fields}\t}` : 'Record<never, never>'
		return [
			comment(
				`${type.name} (${type.kind})${type.description ? `: ${type.description}` : ''}`,
				'',
			),
			`export type ${typeName.get(type.apiId)} = ${wrapper}<\n\t${body},\n\t${quote(type.apiId)}\n>\n`,
		].join('')
	}

	const declarations = types.map(declaration)
	const unions = [
		['ContentEntry', entryTypes],
		['ContentBlock', blockTypes],
	] as const
	const unionLines = unions
		.filter(([, members]) => members.length > 0)
		.map(
			([name, members]) =>
				`export type ${name} = ${union(members.map(({ apiId }) => typeName.get(apiId)!))}\n`,
		)

	const imports = SDK_TYPES.filter((name) => used.has(name))
	return [
		'// Generated by `npx @obelism/content types` from the content model.\n',
		"// Don't edit: run it again after the model changes.\n",
		...(imports.length > 0
			? [`\nimport type { ${imports.join(', ')} } from '@obelism/content'\n`]
			: []),
		...declarations.map((text) => `\n${text}`),
		...(unionLines.length > 0 ? ['\n', ...unionLines] : []),
	].join('')
}
